def render_svg_png(svg: Path, png: Path, w: int, h: int) -> None:
    """Rasterise with headless Edge/Chrome (same look as a browser)."""
    import shutil
    import subprocess
    import tempfile
    browsers = [r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
                r"C:\Program Files\Google\Chrome\Application\chrome.exe", "msedge", "google-chrome", "chromium"]
    exe = next((b for b in browsers if Path(b).exists() or shutil.which(b)), None)
    if exe is None:
        print(f"no headless browser found: {png.name} not refreshed")
        return
    with tempfile.TemporaryDirectory() as tmp:
        html = Path(tmp) / "page.html"
        html.write_text(f'<html><body style="margin:0;overflow:hidden"><img src="{svg.as_uri()}" '
                        f'width="{w}" height="{h}"></body></html>', encoding="utf-8")
        out = Path(tmp) / "shot.png"
        subprocess.run([exe, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--allow-file-access-from-files",
                        f"--user-data-dir={tmp}", f"--window-size={w},{h}", f"--screenshot={out}", html.as_uri()],
                       check=True, capture_output=True, timeout=120)
        Image.open(out).convert("RGB").save(png, optimize=True)


