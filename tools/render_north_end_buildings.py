VEC = re.compile(r"Vector2\(([-\d.]+), ([-\d.]+)\)")
RECT = re.compile(r"Rect2\(([-\d.]+), ([-\d.]+), ([-\d.]+), ([-\d.]+)\)")


def const_block(text: str, name: str) -> list[str]:
    start = text.index(f"const {name} := [")
    end = text.index("\n]", start)
    return [ln.strip() for ln in text[start:end].splitlines()[1:] if ln.strip().startswith("{")]


def parse_layout() -> dict:
    text = LAYOUT.read_text(encoding="utf-8")
    roads = []
    for ln in const_block(text, "ROADS"):
        kind = re.search(r'"kind": &"(\w+)"', ln).group(1)
        roads.append((kind, [(float(x), float(y)) for x, y in VEC.findall(ln)]))
    blocks = []
    for ln in const_block(text, "BLOCKS"):
        rects = [tuple(map(float, r)) for r in RECT.findall(ln)]
        blocks.append((rects[0], '"off": true' in ln, rects[1:]))
    lakes = []
    for ln in const_block(text, "LAKES"):
        (cx, cy), (rx, ry) = [(float(x), float(y)) for x, y in VEC.findall(ln)]
        lakes.append((re.search(r'"name": "([^"]+)"', ln).group(1), cx, cy, rx, ry))
    labels = []
    for ln in const_block(text, "STREET_LABELS"):
        m = re.search(r'"text": "([^"]+)", "pos": Vector2\(([-\d.]+), ([-\d.]+)\), "rot": ([-\d.]+)', ln)
        labels.append((m.group(1), float(m.group(2)), float(m.group(3)), float(m.group(4))))
    lagoon = float(re.search(r"const LAGOON_X := ([-\d.]+)", text).group(1))
    start = text.index("const BUILDINGS := [")
    buildings = [tuple(map(float, r)) for r in RECT.findall(text[start:text.index("\n]", start)])]
    return {"roads": roads, "blocks": blocks, "lakes": lakes, "labels": labels, "lagoon": lagoon, "buildings": buildings}


def bounds(layout: dict) -> tuple[float, float, float, float]:
    xs, ys = [], []
    for _, pts in layout["roads"]:
        xs += [p[0] for p in pts]
        ys += [p[1] for p in pts]
    return min(xs) - 20, min(ys) - 20, max(xs) + 40, max(ys) + 20


def colour_key(entry: dict) -> str:
    if entry["category"] == "standin_business":
        return entry["standin"]["subtype"]
    return entry["category"]


def legend_counts(census: dict) -> dict:
    counts = dict(census["counts"])
    counts["out_of_area"] = len(census["out_of_area"])
    for e in census["buildings"]:
        if e["category"] == "standin_business":
            counts[e["standin"]["subtype"]] = counts.get(e["standin"]["subtype"], 0) + 1
    return counts


def shop_letter(entry: dict) -> str:
    return SHOP_LETTERS.get(entry.get("standin", {}).get("shop_type", ""), "")


def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def render_svg(layout: dict, census: dict, box) -> str:
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x0} {y0} {w + LEGEND_W} {h}" '
           f'width="{(w + LEGEND_W) * PNG_SCALE:.0f}" height="{h * PNG_SCALE:.0f}" font-family="Segoe UI, Arial">',
           f'<rect x="{x0}" y="{y0}" width="{w + LEGEND_W}" height="{h}" fill="{BG}"/>',
           f'<rect x="{layout["lagoon"]}" y="{y0}" width="{x1 - layout["lagoon"]}" height="{h}" fill="{WATER}"/>']
    for name, cx, cy, rx, ry in layout["lakes"]:
        out.append(f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" fill="{WATER}"/>')
        out.append(f'<text x="{cx}" y="{cy}" font-size="9" fill="#4a6f8f" text-anchor="middle">{esc(name)}</text>')
    for (bx, by, bw, bh), off, _ in layout["blocks"]:
        out.append(f'<rect x="{bx}" y="{by}" width="{bw}" height="{bh}" fill="{"#e6e2d8" if off else "#ebe7dc"}"/>')
    for kind in ("loc", "ave", "art", "ramp", "highway", "rail"):
        for k, pts in layout["roads"]:
            if k != kind:
                continue
            d = " ".join(f"{x:.1f},{y:.1f}" for x, y in pts)
            if kind == "rail":
                out.append(f'<polyline points="{d}" fill="none" stroke="#6b4a2f" stroke-width="2" stroke-dasharray="5 3"/>')
            else:
                wdt, col = ROAD_STYLE[kind]
                out.append(f'<polyline points="{d}" fill="none" stroke="{col}" stroke-width="{wdt}" stroke-linecap="round" stroke-linejoin="round"/>')
    for entry in census["out_of_area"] + census["buildings"]:
        bx, by, bw, bh = entry["rect_px"]
        col = CATEGORY_COLOURS[colour_key(entry)][0]
        out.append(f'<rect x="{bx}" y="{by}" width="{bw}" height="{bh}" fill="{col}" stroke="#333" stroke-width="0.3">'
                   f'<title>{esc(entry["id"])} · {entry["category"]} · {entry["design_archetype"]}</title></rect>')
        if shop_letter(entry):
            out.append(f'<text x="{bx + bw / 2}" y="{by + bh / 2 + 3}" font-size="8" font-weight="bold" fill="#fff" '
                       f'text-anchor="middle">{shop_letter(entry)}</text>')
    for entry in census.get("unbuilt", []):
        px, py = entry["rect_px"][:2]
        col = CATEGORY_COLOURS[entry["category"]][0] if entry["category"] else "#000"
        out.append(f'<polygon points="{px},{py - 7} {px + 7},{py} {px},{py + 7} {px - 7},{py}" fill="none" stroke="{col}" stroke-width="2">'
                   f'<title>{esc(entry["id"])} (unbuilt)</title></polygon>')
    for text, lx, ly, rot in layout["labels"]:
        out.append(f'<text x="{lx}" y="{ly}" font-size="7" fill="#333" text-anchor="middle" '
                   f'transform="rotate({rot} {lx} {ly})">{esc(text)}</text>')
    lx, ly = x1 + 12, y0 + 24
    out.append(f'<text x="{lx}" y="{ly}" font-size="13" font-weight="bold">North End buildings (as built)</text>')
    counts = legend_counts(census)
    for i, (cat, (col, label)) in enumerate(CATEGORY_COLOURS.items()):
        y = ly + 22 + i * 18
        out.append(f'<rect x="{lx}" y="{y - 9}" width="12" height="10" fill="{col}" stroke="#333" stroke-width="0.4"/>')
        out.append(f'<text x="{lx + 18}" y="{y}" font-size="8.5">{esc(label)} ({counts.get(cat, 0)})</text>')
    y = ly + 22 + len(CATEGORY_COLOURS) * 18
    out.append(f'<polygon points="{lx + 6},{y - 10} {lx + 12},{y - 4} {lx + 6},{y + 2} {lx},{y - 4}" fill="none" stroke="#e0453a" stroke-width="1.5"/>')
    out.append(f'<text x="{lx + 18}" y="{y}" font-size="8.5">Unbuilt roster place (no lot yet) ({len(census.get("unbuilt", []))})</text>')
    out.append(f'<text x="{lx}" y="{y + 22}" font-size="7.5" fill="#555">Shop letters: {esc(SHOP_KEY_1)}</text>')
    out.append(f'<text x="{lx}" y="{y + 32}" font-size="7.5" fill="#555">{esc(SHOP_KEY_2)}</text>')
    out.append(f'<text x="{lx}" y="{y + 50}" font-size="7.5" fill="#555">1 px = {census["meters_per_px"]} m. Generated by</text>')
    out.append(f'<text x="{lx}" y="{y + 60}" font-size="7.5" fill="#555">tools/render_north_end_buildings.py</text>')
    out.append("</svg>")
    return "\n".join(out)


def font(size: int):
    for name in ("segoeui.ttf", "arial.ttf"):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default()


def render_png(layout: dict, census: dict, box) -> Image.Image:
    x0, y0, x1, y1 = box
    s = PNG_SCALE
    img = Image.new("RGB", (round((x1 - x0 + LEGEND_W) * s), round((y1 - y0) * s)), BG)
    d = ImageDraw.Draw(img)

    def p(x, y):
        return ((x - x0) * s, (y - y0) * s)

    def rect(r, **kw):
        bx, by, bw, bh = r
        d.rectangle([p(bx, by), p(bx + bw, by + bh)], **kw)

    d.rectangle([p(layout["lagoon"], y0), p(x1, y1)], fill=WATER)
    for _, cx, cy, rx, ry in layout["lakes"]:
        d.ellipse([p(cx - rx, cy - ry), p(cx + rx, cy + ry)], fill=WATER)
    for r, off, _ in layout["blocks"]:
        rect(r, fill="#e6e2d8" if off else "#ebe7dc")
    for kind in ("loc", "ave", "art", "ramp", "highway", "rail"):
        for k, pts in layout["roads"]:
            if k != kind:
                continue
            xy = [p(*q) for q in pts]
            if kind == "rail":
                d.line(xy, fill="#6b4a2f", width=round(2 * s))
                continue
            wdt, col = ROAD_STYLE[kind]
            d.line(xy, fill=col, width=round(wdt * s), joint="curve")
            r = wdt * s / 2
            for q in (xy[0], xy[-1]):
                d.ellipse([q[0] - r, q[1] - r, q[0] + r, q[1] + r], fill=col)
    fs = font(round(8 * s))
    for entry in census["out_of_area"] + census["buildings"]:
        rect(entry["rect_px"], fill=CATEGORY_COLOURS[colour_key(entry)][0], outline="#333")
        if shop_letter(entry):
            bx, by, bw, bh = entry["rect_px"]
            d.text(p(bx + bw / 2, by + bh / 2), shop_letter(entry), font=fs, fill="#fff", anchor="mm")
    for entry in census.get("unbuilt", []):
        cx, cy = p(*entry["rect_px"][:2])
        r = 7 * s
        col = CATEGORY_COLOURS[entry["category"]][0] if entry["category"] else "#000"
        d.polygon([(cx, cy - r), (cx + r, cy), (cx, cy + r), (cx - r, cy)], outline=col, width=round(2 * s))
    f = font(round(7 * s))
    for text, lx, ly, rot in layout["labels"]:
        tw = d.textlength(text, font=f)
        tile = Image.new("RGBA", (round(tw) + 4, round(10 * s)), (0, 0, 0, 0))
        ImageDraw.Draw(tile).text((2, 0), text, font=f, fill="#333")
        tile = tile.rotate(-rot, expand=True)
        cx, cy = p(lx, ly)
        img.paste(tile, (round(cx - tile.width / 2), round(cy - tile.height / 2 - 3 * s)), tile)
    lx, ly = (x1 - x0 + 12) * s, 14 * s
    d.text((lx, ly), "North End buildings (as built)", font=font(round(13 * s)), fill="#000")
    counts = legend_counts(census)
    fl = font(round(8.5 * s))
    y = ly + 26 * s
    for cat, (col, label) in CATEGORY_COLOURS.items():
        d.rectangle([lx, y, lx + 12 * s, y + 10 * s], fill=col, outline="#333")
        d.text((lx + 18 * s, y - 1 * s), f"{label} ({counts.get(cat, 0)})", font=fl, fill="#000")
        y += 18 * s
    c = (lx + 6 * s, y + 5 * s)
    r = 6 * s
    d.polygon([(c[0], c[1] - r), (c[0] + r, c[1]), (c[0], c[1] + r), (c[0] - r, c[1])], outline="#e0453a", width=round(1.5 * s))
    d.text((lx + 18 * s, y - 1 * s), f"Unbuilt roster place ({len(census.get('unbuilt', []))})", font=fl, fill="#000")
    fk = font(round(7.5 * s))
    d.text((lx, y + 24 * s), "Shop letters: " + SHOP_KEY_1, font=fk, fill="#555")
    d.text((lx, y + 34 * s), SHOP_KEY_2, font=fk, fill="#555")
    d.text((lx, y + 50 * s), f"1 px = {census['meters_per_px']} m", font=fk, fill="#555")
    return img


def replace_block(lines: list[str], markers: tuple[str, str], new: list[str], insert_at) -> list[str]:
    if markers[0] in lines:
        a, b = lines.index(markers[0]), lines.index(markers[1])
        return lines[:a] + new + lines[b + 1:]
    i = insert_at(lines)
    return lines[:i] + new + lines[i:]


# As-built wireframe: the source drawing's annotation layers (district fills, names, icons, legend)
# over the network the game actually builds. Source network elements are dropped and redrawn
# from the layout at true width (1.2 m/px), so the picture can never drift from the game again.
NET_CLASSES = {"blk", "blk-off", "bldg", "lot", "road-loc", "road-loc-in", "road-ave", "road-ave-in", "road-art", "road-art-in"}
NET_STROKES = {"#7a4c05", "#f3a712", "#f6c35a"}
WATER_FILL = 'fill="#bfe0f2"'
TRUE_WIDTH = {k: w / 1.2 for k, w in {"loc": 9.0, "ave": 12.0, "art": 16.0, "highway": 26.0, "ramp": 8.0}.items()}
ASBUILT_ROAD = {  # kind: (casing colour, inner colour); widths are TRUE_WIDTH
    "loc": ("#c9c4bb", "#fbfaf8"), "ave": ("#a9a399", "#ffffff"), "art": ("#8f897f", "#fff6dc"),
    "highway": ("#7a4c05", "#f3a712"), "ramp": ("#7a4c05", "#f6c35a"),
}


def is_source_network(line: str) -> bool:
    cls = re.search(r'class="([^"]+)"', line)
    if cls and cls.group(1) in NET_CLASSES:
        return True
    stroke = re.search(r'^<path[^>]*stroke="(#\w+)"', line)
    if stroke and (stroke.group(1) in NET_STROKES or (stroke.group(1) == "#5c574f" and "M948" not in line)):
        return True  # I-59, drawn ramps, drawn underpasses (the lagoon bridge at x 948+ stays)
    return line.startswith("<path") and WATER_FILL in line and "L1020.0" not in line  # lakes (not the lagoon)


def poly_d(pts) -> str:
    return "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts)


def asbuilt_network(layout: dict) -> tuple[list[str], list[str]]:
    ground = ["<!-- as-built network: generated from scripts/world/north_end_layout.gd -->"]
    for name, cx, cy, rx, ry in layout["lakes"]:
        ground.append(f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" fill="#bfe0f2" stroke="#6aaed6" stroke-width="1.4"><title>{esc(name)}</title></ellipse>')
    for (bx, by, bw, bh), off, lots in layout["blocks"]:
        ground.append(f'<rect x="{bx}" y="{by}" width="{bw}" height="{bh}" class="{"blk-off" if off else "blk"}"/>')
        for lx, ly, lw, lh in lots:
            ground.append(f'<rect x="{lx}" y="{ly}" width="{lw}" height="{lh}" fill="none" stroke="#dcd7cf" stroke-width="0.6"/>')
    for bx, by, bw, bh in layout["buildings"]:
        ground.append(f'<rect x="{bx}" y="{by}" width="{bw}" height="{bh}" class="bldg"/>')
    roads = []
    for kinds in (("loc",), ("ave",), ("art",), ("highway",), ("ramp",)):
        group = [(k, pts) for k, pts in layout["roads"] if k in kinds]
        for layer in (0, 1):
            for kind, pts in group:
                width = TRUE_WIDTH[kind] - (0 if layer == 0 else 1.6 if kind in ("loc", "ave", "art") else 3.0)
                roads.append(f'<path d="{poly_d(pts)}" stroke="{ASBUILT_ROAD[kind][layer]}" stroke-width="{width:.2f}" fill="none" '
                             f'stroke-linecap="{"round" if kind in ("loc", "ave") else "butt"}" stroke-linejoin="round"/>')
        if kinds == ("highway",):
            for _, pts in group:
                roads.append(f'<path d="{poly_d(pts)}" stroke="#7a4c05" stroke-width="1.2" stroke-dasharray="8 6" fill="none"/>')
    known = {(t, round(x), round(y)) for t, x, y, _ in layout["labels"]}
    roads.append("<!-- /as-built network -->")
    return ground, roads, known


def asbuilt_wireframe(layout: dict) -> list[str]:
    """Source drawing with its network replaced by the as-built one (see is_source_network)."""
    lines = SOURCE_SVG.read_text(encoding="utf-8").splitlines()
    clip = next(i for i, ln in enumerate(lines) if 'clip-path="url(#mapclip)"' in ln)
    end = next(i for i in range(clip, len(lines)) if lines[i].strip() == "</g>")
    ground, roads, known = asbuilt_network(layout)
    body, first, last_geom = [], None, None
    for ln in lines[clip + 1:end]:
        if is_source_network(ln):
            first = len(body) if first is None else first
            if 'class="rlab' not in ln:
                last_geom = len(body)
            continue
        body.append(ln)
    labels = [ln for ln in lines[clip + 1:end] if 'class="rlab' in ln]
    seen = set()
    for ln in labels:
        m = re.search(r'x="([-\d.]+)" y="([-\d.]+)"[^>]*>([^<]*)<', ln)
        seen.add((m.group(3).replace("&amp;", "&"), round(float(m.group(1))), round(float(m.group(2)))))
    for text, x, y, rot in layout["labels"]:  # labels the extractor adds (e.g. Clear Lake Dr)
        if (text, round(x), round(y)) not in seen:
            tf = f' transform="rotate({rot} {x} {y})"' if rot else ""
            labels.append(f'<text x="{x}" y="{y}" class="rlab" text-anchor="middle"{tf}>{esc(text)}</text>')
    body = body[:last_geom] + roads + labels + body[last_geom:]
    body = body[:first] + ground + body[first:]
    head = [ln.replace("Hand-drawn source for tools/extract_north_end_layout.py; the as-built",
                       "AS-BUILT (generated, do not edit): docs/map/north_end_wireframe_source.svg annotations over the")
              .replace("docs/map/north_end_wireframe.svg is generated from the layout by tools/render_north_end_buildings.py.",
                       "network in scripts/world/north_end_layout.gd, by tools/render_north_end_buildings.py.")
            for ln in lines[:clip + 1]]
    return head + body + lines[end:]


def wireframe_overlay(census: dict, base: list[str]) -> None:
    """Census layer on the hand-drawn wireframe: every building by category (stand-in shops lettered),
    unbuilt places as diamonds, and a legend in the legend panel. The extractor ignores these classes."""
    over = [OVERLAY[0], '<g id="census-overlay" opacity="0.85">']
    for entry in census["out_of_area"] + census["buildings"]:
        bx, by, bw, bh = entry["rect_px"]
        col = CATEGORY_COLOURS[colour_key(entry)][0]
        over.append(f'<rect class="cz" x="{bx}" y="{by}" width="{bw}" height="{bh}" fill="{col}" stroke="#222" stroke-width="0.5">'
                    f'<title>{esc(entry["id"])} · {entry["category"]} · {entry["design_archetype"]}</title></rect>')
        if shop_letter(entry):
            over.append(f'<text class="cz" x="{bx + bw / 2}" y="{by + bh / 2 + 3}" font-size="8.5" font-weight="700" '
                        f'fill="#fff" text-anchor="middle">{shop_letter(entry)}</text>')
    for entry in census.get("unbuilt", []):
        px, py = entry["rect_px"][:2]
        col = CATEGORY_COLOURS[entry["category"]][0] if entry["category"] else "#000"
        over.append(f'<polygon class="cz" points="{px},{py - 9} {px + 9},{py} {px},{py + 9} {px - 9},{py}" fill="none" '
                    f'stroke="{col}" stroke-width="2.5"><title>{esc(entry["id"])} (unbuilt: needs a lot)</title></polygon>')
    over += ["</g>", OVERLAY[1]]
    counts = legend_counts(census)
    leg = [LEGEND[0], '<g id="census-legend" font-size="9">',
           '<text class="cz" x="1044" y="1159" font-size="11" font-weight="700">BUILDING CENSUS (overlay)</text>']
    items = list(CATEGORY_COLOURS.items())
    for i, (cat, (col, label)) in enumerate(items):
        x = 1044 + (i % 2) * 230
        y = 1172 + (i // 2) * 13
